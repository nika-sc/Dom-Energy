const int FONT_N = sizeof(FONT) / sizeof(FONT[0]);

// Ищем глиф по UTF-8 последовательности (сравнение строк, не символов)
const uint8_t* glyphFind(const char* code, int len) {
  for (int i = 0; i < FONT_N; i++) {
    const char* g = FONT[i].code;
    if ((int)strlen(g) != len) continue;
    if (memcmp(g, code, len) == 0) return FONT[i].r;
  }
  return 0;   // не нашли
}

// Длина UTF-8 символа по первому байту
int utf8len(unsigned char c) {
  if (c < 0x80) return 1;
  if ((c & 0xE0) == 0xC0) return 2;
  if ((c & 0xF0) == 0xE0) return 3;
  if ((c & 0xF8) == 0xF0) return 4;
  return 1;
}

// Ширина строки в пикселях (по числу символов, не байт)
int txtW(const char* s, uint8_t scale) {
  int n = 0;
  for (const char* p = s; *p; ) { p += utf8len((unsigned char)*p); n++; }
  return n * 6 * scale - scale;
}
